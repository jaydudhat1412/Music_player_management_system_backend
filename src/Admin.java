public class Admin {
    int id;
    String username;
    String name;

    public Admin(int id, String username, String name) {
        this.id = id;
        this.username = username;
        this.name = name;
    }
 int getId() {
        return id;
    }
 String getUsername() {
        return username;
    }
 String getName() {
        return name;
    }
}
